// Writes lib/lineicons.js: node scripts/lineicons-subset.js
//
// @lineiconshq/free-icons is a single 4 MB file of every icon, and
// @lineiconshq/react-native-lineicons re-exports a second full copy (0.0.1).
// Metro cannot tree-shake either, so both used to ship in the app bundle.
// metro.config.js resolves '@lineiconshq/free-icons' to lib/lineicons.js, which
// holds only the icons the source imports. Run this script after importing a
// new icon; __tests__/bundleSize.test.ts fails while the subset is stale.
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const OUT = path.join(ROOT, 'lib', 'lineicons.js')
const SOURCE_DIRS = ['app', 'components', 'hooks', 'lib', 'services', 'theme', 'utils']
const IMPORT = /import\s+(?:type\s+)?\{([^}]*)\}\s*from\s*['"]@lineiconshq\/(?:free-icons|react-native-lineicons)['"]/g

function sourceFiles(dir) {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) return entry.name === '__tests__' ? [] : sourceFiles(full)
    return /\.tsx?$/.test(entry.name) ? [full] : []
  })
}

function usedIconNames() {
  const names = new Set()
  for (const file of SOURCE_DIRS.flatMap((d) => sourceFiles(path.join(ROOT, d)))) {
    for (const match of fs.readFileSync(file, 'utf8').matchAll(IMPORT)) {
      for (const spec of match[1].split(',')) {
        const name = spec.replace(/^\s*type\s+/, '').split(/\s+as\s+/)[0].trim()
        if (name && name !== 'Lineicons') names.add(name)
      }
    }
  }
  return [...names].sort()
}

function allIcons() {
  const dist = path.join(path.dirname(require.resolve('@lineiconshq/free-icons/package.json')), 'dist', 'index.js')
  const icons = {}
  new Function('exports', fs.readFileSync(dist, 'utf8'))(icons)
  return icons
}

function render() {
  const icons = allIcons()
  const lines = usedIconNames().map((name) => {
    if (!icons[name]) throw new Error(`@lineiconshq/free-icons has no icon named ${name}`)
    return `export const ${name} = ${JSON.stringify(icons[name])}`
  })
  return `// Generated by scripts/lineicons-subset.js. Do not edit.\n${lines.join('\n')}\n`
}

if (require.main === module) {
  fs.writeFileSync(OUT, render())
  console.log(`✓ ${path.relative(ROOT, OUT)} (${usedIconNames().length} icons)`)
}

module.exports = { OUT, render, usedIconNames }
